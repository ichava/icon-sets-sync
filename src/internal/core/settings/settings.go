// Lookup returns the key with this name.
func Lookup(name string) (Key, bool) {
	for _, k := range Keys {
		if k.Name == name {
			return k, true
		}
	}
	return Key{}, false
}

// Names returns every key name, sorted.
func Names() []string {
	out := make([]string, len(Keys))
	for i, k := range Keys {
		out[i] = k.Name
	}
	sort.Strings(out)
	return out
}

// Values is a partial layer: only the keys that layer sets.
type Values map[string]any

// Set validates and stores one value.
func (v Values) Set(name string, value any) error {
	key, ok := Lookup(name)
	if !ok {
		return fmt.Errorf("unknown setting %q (known: %s)", name, strings.Join(Names(), ", "))
	}
	coerced, err := key.coerce(value)
	if err != nil {
		return fmt.Errorf("setting %q: %w", name, err)
	}
	v[name] = coerced
	return nil
}

// ParseString converts a raw string (from the environment or --set) to the
// key's type.
func (k Key) ParseString(raw string) (any, error) {
	switch k.Kind {
	case Bool:
		switch strings.ToLower(strings.TrimSpace(raw)) {
		case "1", "t", "true", "yes", "y", "on":
			return true, nil
		case "0", "f", "false", "no", "n", "off":
			return false, nil
		}
		return nil, fmt.Errorf("%q is not a boolean", raw)
	case Int:
		n, err := strconv.Atoi(strings.TrimSpace(raw))
		if err != nil {
			return nil, fmt.Errorf("%q is not an integer", raw)
		}
		return k.coerce(n)
	default:
		return k.coerce(raw)
	}
}

// coerce checks a decoded value against the key's kind and constraints.
//
// Strings must already be strings. YAML reads an unquoted 16.0 as a float, and
// turning that back into "16" would point the emoji recipe at a Unicode
// release that does not exist -- so it is refused and the message says to
// quote it.
func (k Key) coerce(value any) (any, error) {
	switch k.Kind {
	case Bool:
		b, ok := value.(bool)
		if !ok {
			return nil, fmt.Errorf("want a boolean, got %T", value)
		}
		return b, nil

	case Int:
		var n int
		switch x := value.(type) {
		case int:
			n = x
		case int64:
			n = int(x)
		case uint64:
			n = int(x)
		case float64:
			if x != math.Trunc(x) {
				return nil, fmt.Errorf("want an integer, got %v", x)
			}
			n = int(x)
		case json.Number:
			i, err := x.Int64()
			if err != nil {
				return nil, fmt.Errorf("want an integer, got %v", x)
			}
			n = int(i)
		default:
			return nil, fmt.Errorf("want an integer, got %T", value)
		}
		if n < k.Min {
			return nil, fmt.Errorf("must be at least %d, got %d", k.Min, n)
		}
		return n, nil

	default:
		s, ok := value.(string)
		if !ok {
			return nil, fmt.Errorf("want a string, got %T (quote it in YAML)", value)
		}
		if len(k.Enum) > 0 {
			s = strings.ToLower(strings.TrimSpace(s))
			// "warning" is what Python's logging called it, and the legacy
			// ICHAVA_DEV_LOG_LEVEL may still carry it.
			if k.Name == "log_level" && s == "warning" {
				s = "warn"
			}
			for _, e := range k.Enum {
				if s == e {
					return s, nil
				}
			}
			return nil, fmt.Errorf("%q is not one of %s", s, strings.Join(k.Enum, ", "))
		}
		if k.Pattern != nil && !k.Pattern.MatchString(s) {
			return nil, fmt.Errorf("%q does not match %s", s, k.Pattern)
		}
		return s, nil
	}
}

// FromTree flattens a nested document (a config file's contents) into a layer.
//
// Top-level keys beginning with "_" are authoring notes and are skipped, as in
// the pack configs. For LayerPack, a run-wide key is an error.
func FromTree(tree map[string]any, layer Layer) (Values, error) {
	out := Values{}
	var walk func(prefix string, node map[string]any) error
	walk = func(prefix string, node map[string]any) error {
		names := make([]string, 0, len(node))
		for name := range node {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			if prefix == "" && strings.HasPrefix(name, "_") {
				continue
			}
			full := name
			if prefix != "" {
				full = prefix + "." + name
			}
			if child, ok := node[name].(map[string]any); ok {
				if _, isKey := Lookup(full); !isKey {
					if err := walk(full, child); err != nil {
						return err
					}
					continue
				}
			}
			key, ok := Lookup(full)
			if !ok {
				return fmt.Errorf("unknown setting %q", full)
			}
			if layer == LayerPack && !key.PackScoped {
				return fmt.Errorf("setting %q is run-wide and cannot be set in a pack config", full)
			}
			if err := out.Set(full, node[name]); err != nil {
				return err
			}
		}
		return nil
	}
	if err := walk("", tree); err != nil {
		return nil, err
	}
	return out, nil
}

// FromEnv reads every key's environment variable. An empty variable is unset.
// The current name wins over a legacy one.
func FromEnv(lookup func(string) (string, bool)) (Values, error) {
	out := Values{}
	for _, key := range Keys {
		names := append([]string{key.Env}, key.LegacyEnv...)
		for _, env := range names {
			raw, ok := lookup(env)
			if !ok || raw == "" {
				continue
			}
			value, err := key.ParseString(raw)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", env, err)
			}
			out[key.Name] = value
			break
		}
	}
	return out, nil
}

// FromAssignments parses --set key=value pairs.
func FromAssignments(pairs []string) (Values, error) {
	out := Values{}
	for _, pair := range pairs {
		name, raw, ok := strings.Cut(pair, "=")
		if !ok {
			return nil, fmt.Errorf("--set %q: want key=value", pair)
		}
		name = strings.TrimSpace(name)
		key, found := Lookup(name)
		if !found {
			return nil, fmt.Errorf("--set: unknown setting %q (known: %s)", name, strings.Join(Names(), ", "))
		}
		value, err := key.ParseString(raw)
		if err != nil {
			return nil, fmt.Errorf("--set %s: %w", name, err)
		}
		out[name] = value
	}
	return out, nil
}

// Resolved is the merged result, with the layer each value came from.
type Resolved struct {
	values  map[string]any
	origins map[string]Layer
}

// LayerValues pairs a layer with its values, for Resolve.
type LayerValues struct {
	Layer  Layer
	Values Values
}

// Resolve merges layers over the defaults. Pass them lowest precedence first;
// a later layer replaces an earlier one key by key.
func Resolve(layers ...LayerValues) Resolved {
	r := Resolved{values: map[string]any{}, origins: map[string]Layer{}}
	for _, k := range Keys {
		r.values[k.Name] = k.Default
		r.origins[k.Name] = LayerDefault
	}
	for _, l := range layers {
		for name, v := range l.Values {
			r.values[name] = v
			r.origins[name] = l.Layer
		}
	}
	return r
}

// Stack holds the layers that do not vary by pack.
type Stack struct {
	Global Values
	Env    Values
	Flags  Values
}

// Resolve merges the stack over one pack's values (nil for run-wide settings),
// in the documented precedence.
func (s Stack) Resolve(pack Values) Resolved {
	return Resolve(
		LayerValues{LayerPack, pack},
		LayerValues{LayerGlobal, s.Global},
		LayerValues{LayerEnv, s.Env},
		LayerValues{LayerFlag, s.Flags},
	)
}

// String returns a string setting. It panics on an unknown name, which is a
// programming error rather than a configuration one.
func (r Resolved) String(name string) string { return r.get(name).(string) }

// Bool returns a boolean setting.
func (r Resolved) Bool(name string) bool { return r.get(name).(bool) }

// Int returns an integer setting.
func (r Resolved) Int(name string) int { return r.get(name).(int) }

func (r Resolved) get(name string) any {
	v, ok := r.values[name]
	if !ok {
		panic("settings: unknown key " + name)
	}
	return v
}

// Origin returns the layer that supplied a value.
func (r Resolved) Origin(name string) Layer { return r.origins[name] }

// FromAbove reports whether a value was set above the pack layer -- by the
// global config, the environment or a flag. A per-sink field in a pack config
// is pack-layer too, and gives way only to these.
func (r Resolved) FromAbove(name string) bool {
	switch r.origins[name] {
	case LayerGlobal, LayerEnv, LayerFlag:
		return true
	}
	return false
}

// Tree returns the values as a nested map, for printing.
func (r Resolved) Tree() map[string]any {
	out := map[string]any{}
	for _, name := range Names() {
		node := out
		parts := strings.Split(name, ".")
		for _, p := range parts[:len(parts)-1] {
			child, ok := node[p].(map[string]any)
			if !ok {
				child = map[string]any{}
				node[p] = child
			}
			node = child
		}
		node[parts[len(parts)-1]] = r.values[name]
	}
	return out
}

// Origins returns name -> layer for every key.
func (r Resolved) Origins() map[string]string {
	out := make(map[string]string, len(r.origins))
	for k, v := range r.origins {
		out[k] = string(v)
	}
	return out
}

// Settings is the typed view of a resolution.
type Settings struct {
	ConfigDir        string
	PrivateConfigDir string
	LogLevel         string
	Concurrency      int
	Workspace        string
	DryRun           bool
	Force            bool
	Git              Git
	Emoji            Emoji
}

// Git is the git and pull-request settings.
type Git struct {
	Author        string
	Base          string
	Branch        string
	CommitSubject string
	CommitBody    string
	OpenPR        bool
}

// Emoji is the emoji recipe's upstream versions.
type Emoji struct {
	UnicodeVersion  string
	OpenMojiVersion string
}

// Settings returns the typed view.
func (r Resolved) Settings() Settings {
	return Settings{
		ConfigDir:        r.String("config_dir"),
		PrivateConfigDir: r.String("private_config_dir"),
		LogLevel:         r.String("log_level"),
		Concurrency:      r.Int("concurrency"),
		Workspace:        r.String("workspace"),
		DryRun:           r.Bool("dry_run"),
		Force:            r.Bool("force"),
		Git: Git{
			Author:        r.String("git.author"),
			Base:          r.String("git.base"),
			Branch:        r.String("git.branch"),
			CommitSubject: r.String("git.commit_subject"),
			CommitBody:    r.String("git.commit_body"),
			OpenPR:        r.Bool("git.open_pr"),
		},
		Emoji: Emoji{
			UnicodeVersion:  r.String("emoji.unicode_version"),
			OpenMojiVersion: r.String("emoji.openmoji_version"),
		},
	}
}
