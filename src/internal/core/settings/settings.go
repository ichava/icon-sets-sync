// Package settings resolves the tool's runtime settings from five layers.
//
// Precedence, lowest first:
//
//	defaults < pack config `settings` < global config < ICHAVA_* env < flags
//
// Each layer is a partial set of values keyed by a dotted name ("git.base").
// Resolution records which layer supplied every value, so `config print` can
// say why a value is what it is -- the question that matters when a scheduled
// run behaves differently from a laptop.
//
// The key registry below is the single list of what can be set. A layer that
// names a key not in it is an error rather than an ignored typo: a misspelt
// `dry_rnu: true` that silently did nothing would commit and open a pull
// request the operator had asked not to.
package settings

import (
	"encoding/json"
	"fmt"
	"math"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Layer names where a value came from.
type Layer string

// The five layers, as reported by Origin.
const (
	LayerDefault Layer = "default"
	LayerPack    Layer = "pack"
	LayerGlobal  Layer = "global"
	LayerEnv     Layer = "env"
	LayerFlag    Layer = "flag"
)

// Precedence lists the layers lowest first. Resolve applies them in this order.
var Precedence = []Layer{LayerDefault, LayerPack, LayerGlobal, LayerEnv, LayerFlag}

// Kind is a setting's value type.
type Kind int

// The value types a setting can hold.
const (
	String Kind = iota
	Bool
	Int
)

func (k Kind) String() string {
	switch k {
	case Bool:
		return "boolean"
	case Int:
		return "integer"
	default:
		return "string"
	}
}

// Key describes one setting.
type Key struct {
	// Name is the dotted name used in config files, --set and output.
	Name string
	Kind Kind

	// Default is the value when no layer sets it.
	Default any

	// Env is the environment variable that sets it. LegacyEnv lists older
	// names still honoured, lower precedence than Env.
	Env       string
	LegacyEnv []string

	// PackScoped keys may appear in a pack config's `settings`. Run-wide keys
	// (where configs live, how many packs run at once, how loud the log is)
	// cannot: one pack cannot meaningfully decide them for a run of four.
	PackScoped bool

	// Enum restricts a string to these values. Min bounds an integer.
	Enum []string
	Min  int

	// Pattern, when set, must match a string value.
	Pattern *regexp.Regexp

	Help string
}

